let currentCategory = "";

let quizData = [];

let currentIndex = 0;

let score = 0;


const categories = Object.keys(allQuizCollections);

const categoryButtonsContainer = document.getElementById('category-buttons');

const defDisplay = document.getElementById('definition-text');

